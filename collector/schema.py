"""Egress payload contract: the ONLY shape allowed to leave the customer environment.

FROZEN. Any change must also regenerate contracts/payload.schema.json
(`python -m collector.export_schema`) and be approved by the SaaS owner.
tests/test_contract_frozen.py fails if the two drift apart.

Anything not declared here has no field to travel in, so raw log text,
usernames, IPs and secrets cannot be sent even if redaction misses them.
"""
from __future__ import annotations

from datetime import datetime, timedelta
from enum import Enum
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

SCHEMA_VERSION = "1.0.0"

UUID_RE = r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"

MetricName = Literal[
    "cpu_pct",
    "mem_pct",
    "disk_pct",
    "bandwidth_mbps",
    "latency_ms",
    "packet_loss_pct",
    "service_up",
    "connectivity_up",
]
MetricUnit = Literal["%", "mbps", "ms", "bool"]

METRIC_UNITS: dict[str, str] = {
    "cpu_pct": "%",
    "mem_pct": "%",
    "disk_pct": "%",
    "bandwidth_mbps": "mbps",
    "latency_ms": "ms",
    "packet_loss_pct": "%",
    "service_up": "bool",
    "connectivity_up": "bool",
}
METRIC_NAMES = tuple(METRIC_UNITS)

EventCategory = Literal[
    "auth_failure",
    "auth_failure_burst",
    "service_state",
    "network_event",
    "security_event",
    "log_event",
]
Severity = Literal["info", "warning", "high", "critical"]


class HealthState(str, Enum):
    EXCELLENT = "Excellent"
    GOOD = "Good"
    FAIR = "Fair"
    POOR = "Poor"


class Metric(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: MetricName
    value: float = Field(allow_inf_nan=False)
    unit: MetricUnit

    @model_validator(mode="after")
    def _unit_matches_name(self) -> "Metric":
        if METRIC_UNITS[self.name] != self.unit:
            raise ValueError(f"unit for {self.name} must be {METRIC_UNITS[self.name]}")
        return self


class Event(BaseModel):
    model_config = ConfigDict(extra="forbid")

    category: EventCategory
    severity: Severity
    count: int = Field(ge=1, le=1_000_000)
    # Template-generated by the collector, never copied from raw text.
    summary: str = Field(max_length=120, pattern=r"^[A-Za-z0-9 ,.:;()_%/-]*$")


class Payload(BaseModel):
    model_config = ConfigDict(extra="forbid")

    payload_id: str = Field(pattern=UUID_RE)
    tenant_ref: str = Field(pattern=r"^t-[a-z0-9-]{1,40}$")
    collector_id: str = Field(pattern=r"^col-[a-z0-9-]{1,40}$")
    source_id: str = Field(pattern=r"^src_[0-9a-f]{8,16}$")
    region: str = Field(pattern=r"^[a-z]{2,6}(-[a-z0-9]+)?$")
    event_ts_utc: datetime
    source_tz: str = Field(pattern=r"^[A-Za-z0-9_+/-]{1,64}$")
    window_s: int = Field(ge=1, le=3600)
    metric: Optional[Metric] = None
    event: Optional[Event] = None
    health_state: HealthState
    collector_version: str = Field(pattern=r"^\d+\.\d+\.\d+$")

    @field_validator("event_ts_utc")
    @classmethod
    def _must_be_utc(cls, v: datetime) -> datetime:
        if v.tzinfo is None or v.utcoffset() != timedelta(0):
            raise ValueError("event_ts_utc must be timezone-aware UTC")
        return v

    @model_validator(mode="after")
    def _exactly_one_body(self) -> "Payload":
        if (self.metric is None) == (self.event is None):
            raise ValueError("exactly one of metric or event is required")
        return self
